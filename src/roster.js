export function getSpecimen(id) {
  return ROSTER.find((s) => s.id === id) || ROSTER[0];
}

export function buildMoves(def) {
  const out = {};
  for (const [key, move] of Object.entries(BASE_MOVES)) {
    out[key] = {
      ...move,
      startup: move.startup / def.atkSpeed,
      active: move.active / def.atkSpeed,
      recovery: move.recovery / def.atkSpeed,
      dmg: move.dmg * def.dmg,
      ox: move.ox * def.reach,
      w: move.w * def.reach,
    };
  }
  out.special = {
    ...def.special.move,
    name: def.special.name,
    cost: def.special.cost,
    startup: def.special.move.startup / def.atkSpeed,
    recovery: def.special.move.recovery / def.atkSpeed,
    hitstop: def.special.move.hitstop ?? 0.06,
  };
  return out;
}
